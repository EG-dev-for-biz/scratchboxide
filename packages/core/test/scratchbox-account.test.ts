/**
 * Sign in with scratchbox.ai (scratchbox-account.ts) against a local HTTP server implementing the contract in
 * docs/research/2026-11-11-scratchbox-account-sign-in-plan.md: the token exchange checks the PKCE verifier against the
 * challenge the start URL carried and the redirect URI, the revoke checks the Bearer credential, and the MCP route
 * refuses a revoked credential with 401. The key store is a real FileKeyStore in a temporary directory, so what is
 * stored (and forgotten) is read back from disk. Every credential here is generated by the test.
 */

import * as crypto from 'crypto';
import * as fs from 'fs';
import * as http from 'http';
import * as os from 'os';
import * as path from 'path';
import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';
import { FileKeyStore, defaultCredentialsPath } from '../src/node/key-store';
import { ACCOUNT_KEYS, AccountError, PENDING_SIGN_IN_MS, ScratchboxAccount, accountBaseUrl, loopbackRedirectUri, pkceChallenge, pkcePair } from '../src/node/scratchbox-account/scratchbox-account';
import { callStudioTool, studioMcpConfig, studioMcpHeaders, StudioMcpError } from '../src/node/scratchbox-studio/studio-mcp-client';

const b64url = (b: Buffer) => b.toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
const newCredential = () => `sbmcp_${b64url(crypto.randomBytes(32))}`;
const DAY = 86_400_000;

let server: http.Server;
let base = '';
let tmp = '';
/** What the consent page saw (from the start URL), keyed by the code it issued. */
const issued = new Map<string, { challenge: string; redirectUri: string }>();
const live = new Set<string>();
let tokenCalls = 0;
let expiresInMs = 90 * DAY;
const mcpSeen: http.IncomingHttpHeaders[] = [];

function json(res: http.ServerResponse, status: number, body: unknown) { res.writeHead(status, { 'content-type': 'application/json' }); res.end(JSON.stringify(body)); }

beforeAll(async () => {
    tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'sb-account-'));
    server = http.createServer((req, res) => {
        let raw = '';
        req.on('data', c => { raw += c; });
        req.on('end', () => {
            const auth = String(req.headers.authorization ?? '');
            const bearer = auth.startsWith('Bearer ') ? auth.slice(7) : '';
            if (req.method === 'POST' && req.url === '/api/auth/desktop/token') {
                tokenCalls++;
                const body = JSON.parse(raw);
                const grant = issued.get(body.code);
                issued.delete(body.code);
                if (!grant) return json(res, 400, { success: false, error: 'invalid_grant' });
                if (grant.redirectUri !== body.redirect_uri) return json(res, 400, { success: false, error: 'invalid_grant' });
                if (pkceChallenge(String(body.code_verifier)) !== grant.challenge) return json(res, 400, { success: false, error: 'invalid_grant' });
                const credential = newCredential();
                live.add(credential);
                return json(res, 200, { success: true, data: { credential, expiresAt: new Date(Date.now() + expiresInMs).toISOString(), user: { id: 42, username: 'ada', email: 'ada@example.test', tier: 'pro' }, workspace: { id: 217, name: 'Studio <One>' } } });
            }
            if (req.method === 'POST' && req.url === '/api/auth/desktop/revoke') {
                if (!live.delete(bearer)) return json(res, 401, { success: false, error: 'Unauthorized' });
                return json(res, 200, { success: true });
            }
            if (req.method === 'POST' && req.url === '/api/mcp/canvas') {
                mcpSeen.push(req.headers);
                if (!live.has(bearer)) return json(res, 401, { error: 'Unauthorized' });
                res.writeHead(200, { 'content-type': 'text/event-stream' });
                res.end(`event: message\ndata: ${JSON.stringify({ jsonrpc: '2.0', id: 1, result: { content: [{ type: 'text', text: '' }], structuredContent: { user: 'ada', workspace: req.headers['x-scratchbox-workspace-id'] } } })}\n\n`);
                return;
            }
            json(res, 404, { error: 'not found' });
        });
    });
    await new Promise<void>(r => server.listen(0, '127.0.0.1', () => r()));
    base = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
});

afterAll(async () => {
    await new Promise<void>(r => server.close(() => r()));
    fs.rmSync(tmp, { recursive: true, force: true });
});

let n = 0;
function account(now?: () => number) {
    const filePath = path.join(tmp, `credentials-${++n}.json`);
    const store = new FileKeyStore({ filePath });
    return { account: new ScratchboxAccount({ store, env: { SCRATCHBOX_ACCOUNT_URL: base }, ...(now ? { now } : {}) }), store, filePath };
}

/** What scratchbox.ai's consent page does: read the start URL, issue a code bound to its challenge and redirect URI. */
function consent(startUrl: string): { code: string; state: string; redirectUri: string } {
    const u = new URL(startUrl);
    const code = b64url(crypto.randomBytes(16));
    const redirectUri = u.searchParams.get('redirect_uri')!;
    issued.set(code, { challenge: u.searchParams.get('code_challenge')!, redirectUri });
    return { code, state: u.searchParams.get('state')!, redirectUri };
}

beforeEach(() => { expiresInMs = 90 * DAY; });

describe('PKCE and the start URL', () => {
    it('makes an S256 challenge from the verifier (RFC 7636 appendix B vector)', () => {
        expect(pkceChallenge('dBjftJeZ4CVP-mB92K27uhbUJU1p1r_wW1gFWFOEjXk')).toBe('E9Melhoa2OwvFrEMTJguCHaoeK1t8URWbuGJSstw-cM');
        const { verifier, challenge } = pkcePair();
        expect(verifier).toMatch(/^[A-Za-z0-9_-]{43,128}$/);
        expect(challenge).toBe(pkceChallenge(verifier));
    });

    it('points the consent page at this server\'s loopback callback, with a fresh state each time', () => {
        const { account: a } = account();
        const one = a.start({ port: 3071, device: 'test-mac' });
        const two = a.start({ port: 3071, device: 'test-mac' });
        const u = new URL(one.url);
        expect(`${u.origin}${u.pathname}`).toBe(`${base}/connect/desktop`);
        expect(u.searchParams.get('client_id')).toBe('scratchbox-ide');
        expect(u.searchParams.get('redirect_uri')).toBe('http://127.0.0.1:3071/auth/scratchbox/callback');
        expect(u.searchParams.get('code_challenge_method')).toBe('S256');
        expect(u.searchParams.get('code_challenge')).toMatch(/^[A-Za-z0-9_-]{43}$/);
        expect(u.searchParams.get('state')).toBe(one.state);
        expect(one.state).not.toBe(two.state);
        expect(loopbackRedirectUri(9)).toBe('http://127.0.0.1:9/auth/scratchbox/callback');
        expect(() => a.start({ port: 0 })).toThrow(AccountError);
        expect(accountBaseUrl({})).toBe('https://www.scratchbox.ai');
    });
});

describe('completing a sign-in', () => {
    it('exchanges the code with the verifier, keeps the credential encrypted on disk and reports who is signed in', async () => {
        const { account: a, filePath } = account();
        const grant = consent(a.start({ port: 3071 }).url);
        const profile = await a.complete({ code: grant.code, state: grant.state });
        expect(profile.user).toEqual({ id: 42, username: 'ada', email: 'ada@example.test', tier: 'pro' });
        expect(profile.workspace).toEqual({ id: 217, name: 'Studio <One>' });

        const status = await a.status();
        expect(status).toMatchObject({ signedIn: true, baseUrl: base, user: { username: 'ada' }, workspace: { id: 217 }, expiresSoon: false });
        expect(JSON.stringify(status)).not.toMatch(/sbmcp_/);

        const cred = await a.credential();
        expect(cred?.token).toMatch(/^sbmcp_[A-Za-z0-9_-]{43}$/);
        expect(a.credentialSync()).toEqual(cred);
        const onDisk = fs.readFileSync(filePath, 'utf8');
        expect(onDisk).not.toContain(cred!.token);
        expect(onDisk).not.toContain('ada@example.test');
    });

    it('uses each state once', async () => {
        const { account: a } = account();
        const grant = consent(a.start({ port: 3071 }).url);
        await a.complete({ code: grant.code, state: grant.state });
        const calls = tokenCalls;
        await expect(a.complete({ code: grant.code, state: grant.state })).rejects.toMatchObject({ code: 'invalid_state' });
        expect(tokenCalls).toBe(calls);
    });

    it('refuses a state it never started, without calling scratchbox.ai', async () => {
        const { account: a } = account();
        const calls = tokenCalls;
        await expect(a.complete({ code: 'x', state: 'forged' })).rejects.toMatchObject({ code: 'invalid_state' });
        await expect(a.complete({ code: 'x' })).rejects.toMatchObject({ code: 'invalid_state' });
        expect(tokenCalls).toBe(calls);
    });

    it('refuses a sign-in older than 10 minutes', async () => {
        let t = 1_000_000;
        const { account: a } = account(() => t);
        const grant = consent(a.start({ port: 3071 }).url);
        t += PENDING_SIGN_IN_MS + 1;
        await expect(a.complete({ code: grant.code, state: grant.state })).rejects.toMatchObject({ code: 'invalid_state' });
    });

    it('reports a declined consent and keeps nothing', async () => {
        const { account: a } = account();
        const grant = consent(a.start({ port: 3071 }).url);
        await expect(a.complete({ state: grant.state, error: 'access_denied' })).rejects.toMatchObject({ code: 'access_denied' });
        expect((await a.status()).signedIn).toBe(false);
    });

    it('fails when the verifier does not match (a code stolen into another server\'s sign-in)', async () => {
        const { account: victim } = account();
        const { account: attacker } = account();
        const stolen = consent(victim.start({ port: 3071 }).url);
        const theirs = attacker.start({ port: 3071 });
        // The attacker's own state with the victim's code: the attacker's verifier does not match the victim's challenge.
        await expect(attacker.complete({ code: stolen.code, state: theirs.state })).rejects.toMatchObject({ code: 'invalid_grant' });
        expect((await attacker.status()).signedIn).toBe(false);
    });

    it('marks a credential inside a week of its end as ending soon, and an ended one as signed out', async () => {
        let t = Date.now();
        const { account: a } = account(() => t);
        expiresInMs = 3 * DAY;
        const grant = consent(a.start({ port: 3071 }).url);
        await a.complete({ code: grant.code, state: grant.state });
        expect((await a.status())).toMatchObject({ signedIn: true, expiresSoon: true });
        t += 4 * DAY;
        expect((await a.status())).toMatchObject({ signedIn: false });
        expect(await a.credential()).toBeUndefined();
    });
});

describe('signing out and a revoked credential', () => {
    it('revokes on scratchbox.ai and forgets the credential', async () => {
        const { account: a, store } = account();
        const grant = consent(a.start({ port: 3071 }).url);
        await a.complete({ code: grant.code, state: grant.state });
        const token = (await a.credential())!.token;
        expect(live.has(token)).toBe(true);
        expect(await a.signOut()).toEqual({ revoked: true });
        expect(live.has(token)).toBe(false);
        expect(await store.getPassword(ACCOUNT_KEYS.service, ACCOUNT_KEYS.credential)).toBeUndefined();
        expect((await a.status()).signedIn).toBe(false);
    });

    it('sends the credential as Bearer to the Studio MCP, and forgets it when scratchbox.ai answers 401', async () => {
        const { account: a } = account();
        const grant = consent(a.start({ port: 3071 }).url);
        await a.complete({ code: grant.code, state: grant.state });
        const config = studioMcpConfig({}, a)!;
        expect(config).toMatchObject({ endpoint: `${base}/api/mcp/canvas`, workspaceId: '217' });
        expect(studioMcpHeaders(config)).toEqual({ Authorization: `Bearer ${config.credential}`, 'x-scratchbox-workspace-id': '217' });

        const ok = await callStudioTool(config, 'auth.whoami', {}, { onCredentialRejected: () => a.rejected() });
        expect(ok).toEqual({ user: 'ada', workspace: '217' });
        expect(mcpSeen.at(-1)?.['x-internal-secret']).toBeUndefined();

        live.delete(config.credential!); // revoked from scratchbox.ai's settings
        await expect(callStudioTool(config, 'auth.whoami', {}, { onCredentialRejected: () => a.rejected() })).rejects.toThrow(/no longer accepts this sign-in/);
        const status = await a.status();
        expect(status.signedIn).toBe(false);
        expect(status.reason).toMatch(/revoked or expired/);
        expect(studioMcpConfig({}, a)).toBeUndefined();
    });

    it('prefers the signed-in credential over the development secret, and refuses with no connection at all', () => {
        const { account: a } = account();
        const dev = studioMcpConfig({ SCRATCHBOX_MCP_SECRET: 's', SCRATCHBOX_MCP_USER_ID: '1', SCRATCHBOX_MCP_WORKSPACE_ID: '9' }, a)!;
        expect(dev.credential).toBeUndefined();
        expect(studioMcpHeaders(dev)).toMatchObject({ 'x-internal-secret': 's' });
        expect(() => studioMcpHeaders({ endpoint: base, workspaceId: '9' })).toThrow(StudioMcpError);
    });
});

describe('an isolated key store', () => {
    it('reads SCRATCHBOX_CREDENTIALS_FILE so a second instance keeps its own keys and sign-in', () => {
        const before = process.env.SCRATCHBOX_CREDENTIALS_FILE;
        try {
            delete process.env.SCRATCHBOX_CREDENTIALS_FILE;
            expect(defaultCredentialsPath()).toBe(path.join(os.homedir(), '.scratchbox', 'credentials.json'));
            process.env.SCRATCHBOX_CREDENTIALS_FILE = path.join(tmp, 'isolated.json');
            expect(defaultCredentialsPath()).toBe(path.join(tmp, 'isolated.json'));
        } finally {
            if (before === undefined) delete process.env.SCRATCHBOX_CREDENTIALS_FILE; else process.env.SCRATCHBOX_CREDENTIALS_FILE = before;
        }
    });
});
