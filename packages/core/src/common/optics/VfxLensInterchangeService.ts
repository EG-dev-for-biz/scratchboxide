import type { LensDistortionParams } from '../vfx-plate-protocol';

export interface VfxLensMetadata {
    lensName?: string;
    cameraBody?: string;
    focalLengthMm?: number;
    filmBackWidthMm?: number;
    filmBackHeightMm?: number;
    resolutionWidth?: number;
    resolutionHeight?: number;
    outputMode?: 'undistort' | 'redistort' | 'stmap';
}

export interface OpenCvCameraCalibration {
    imageWidth: number;
    imageHeight: number;
    cameraMatrix: [
        [number, number, number],
        [number, number, number],
        [number, number, number]
    ];
    distortionCoefficients: number[]; // [k1, k2, p1, p2, k3, k4, k5, k6]
    focalLengthPx: [number, number];   // [fx, fy]
    principalPointPx: [number, number];// [cx, cy]
    model: string;
}

/**
 * Professional Visual Effects (VFX) Lens Distortion Interchange Service.
 * Provides bidirectional interchange formats between Scratchbox and industry
 * toolsets: 3DEqualizer 4 (.lens), Foundry Nuke LensDistortion, OpenCV, and ST Maps.
 */
export class VfxLensInterchangeService {

    /**
     * Exports a standard 3DEqualizer 4 (.lens) file format.
     * Compatible with 3DE4 Matchmove and Nuke 3DE4 Lens Distortion plugins.
     */
    public static export3DEqualizerLensFile(
        params: LensDistortionParams,
        metadata: VfxLensMetadata = {}
    ): string {
        const focal = params.focalLengthMm ?? metadata.focalLengthMm ?? 35.0;
        const sensorW = params.sensorWidthMm ?? metadata.filmBackWidthMm ?? 36.0;
        const sensorH = params.sensorHeightMm ?? metadata.filmBackHeightMm ?? 24.0;
        const aspect = params.aspectRatio ?? (metadata.resolutionWidth && metadata.resolutionHeight 
            ? metadata.resolutionWidth / metadata.resolutionHeight 
            : sensorW / sensorH);
        const squeeze = params.anamorphicSqueeze ?? params.squeezeFactor ?? 1.0;
        const oc = params.opticalCenter ?? [0.5, 0.5];

        // 3DEqualizer expresses offset from center in normalized filmback
        const offsetX = (oc[0] - 0.5);
        const offsetY = (oc[1] - 0.5);

        const lines: string[] = [
            '# 3DEqualizer4 Lens Distortion File',
            '# Generated by Scratchbox IDE VFX Lens Engine',
            `# Lens: ${metadata.lensName ?? 'Standard VFX Calibrated Lens'}`,
            `# Camera: ${metadata.cameraBody ?? 'VFX Camera Sensor'}`,
            '',
            `distortion_model ${squeeze > 1.05 || params.model === 'anamorphic_deg4' ? '3de4_anamorphic_standard_degree_4' : '3de4_radial_standard_degree_4'}`,
            `focal_length ${focal.toFixed(6)}`,
            `film_width ${sensorW.toFixed(6)}`,
            `film_height ${sensorH.toFixed(6)}`,
            `film_aspect_ratio ${aspect.toFixed(6)}`,
            `lens_center_offset_x ${offsetX.toFixed(6)}`,
            `lens_center_offset_y ${offsetY.toFixed(6)}`,
            `squeeze_factor ${squeeze.toFixed(6)}`,
            ''
        ];

        if (squeeze > 1.05 || params.model === 'anamorphic_deg4') {
            lines.push(
                '# Degree 4 Anamorphic Coefficients',
                `c20 ${(params.c20 ?? params.k1).toFixed(8)}`,
                `c02 ${(params.c02 ?? params.k1 * 0.5).toFixed(8)}`,
                `c40 ${(params.c40 ?? params.k2).toFixed(8)}`,
                `c22 ${(params.c22 ?? (params.k2 * 0.7)).toFixed(8)}`,
                `c04 ${(params.c04 ?? (params.k2 * 0.4)).toFixed(8)}`
            );
        } else {
            lines.push(
                '# Radial Coefficients',
                `c02 ${(params.k1).toFixed(8)}`,
                `c04 ${(params.k2).toFixed(8)}`
            );
            if (params.k3 !== undefined) {
                lines.push(`c06 ${(params.k3).toFixed(8)}`);
            }
            if (params.k4 !== undefined) {
                lines.push(`c08 ${(params.k4).toFixed(8)}`);
            }
        }

        if (params.p1 || params.p2) {
            lines.push(
                '',
                '# Decentering / Tangential Terms',
                `p1 ${(params.p1 ?? 0.0).toFixed(8)}`,
                `p2 ${(params.p2 ?? 0.0).toFixed(8)}`
            );
        }

        return lines.join('\n') + '\n';
    }

    /**
     * Parses a 3DEqualizer 4 (.lens) file into structured LensDistortionParams.
     */
    public static parse3DEqualizerLensFile(content: string): LensDistortionParams {
        const result: LensDistortionParams = {
            k1: 0.0,
            k2: 0.0,
            p1: 0.0,
            p2: 0.0,
            anamorphicSqueeze: 1.0,
            opticalCenter: [0.5, 0.5]
        };

        const lines = content.split('\n');
        for (const rawLine of lines) {
            const line = rawLine.trim();
            if (!line || line.startsWith('#')) continue;

            const parts = line.split(/\s+/);
            if (parts.length < 2) continue;

            const key = parts[0].toLowerCase();
            const val = parseFloat(parts[1]);

            switch (key) {
                case 'distortion_model':
                    if (parts[1].includes('anamorphic')) result.model = 'anamorphic_deg4';
                    else result.model = 'brown_conrady';
                    break;
                case 'focal_length':
                    result.focalLengthMm = val;
                    break;
                case 'film_width':
                    result.sensorWidthMm = val;
                    break;
                case 'film_height':
                    result.sensorHeightMm = val;
                    break;
                case 'film_aspect_ratio':
                    result.aspectRatio = val;
                    break;
                case 'squeeze_factor':
                    result.anamorphicSqueeze = val;
                    result.squeezeFactor = val;
                    break;
                case 'lens_center_offset_x':
                    result.opticalCenter![0] = 0.5 + val;
                    break;
                case 'lens_center_offset_y':
                    result.opticalCenter![1] = 0.5 + val;
                    break;
                case 'c02':
                    result.k1 = val;
                    result.c02 = val;
                    break;
                case 'c04':
                    result.k2 = val;
                    result.c04 = val;
                    break;
                case 'c06':
                    result.k3 = val;
                    break;
                case 'c08':
                    result.k4 = val;
                    break;
                case 'c20':
                    result.c20 = val;
                    if (!result.k1) result.k1 = val;
                    break;
                case 'c40':
                    result.c40 = val;
                    break;
                case 'c22':
                    result.c22 = val;
                    break;
                case 'p1':
                    result.p1 = val;
                    break;
                case 'p2':
                    result.p2 = val;
                    break;
            }
        }

        return result;
    }

    /**
     * Exports a Foundry Nuke .nk script snippet and Python API call
     * configuring a Nuke LensDistortion2 node.
     */
    public static exportNukeLensDistortionScript(
        params: LensDistortionParams,
        metadata: VfxLensMetadata = {}
    ): string {
        const oc = params.opticalCenter ?? [0.5, 0.5];
        const squeeze = params.anamorphicSqueeze ?? params.squeezeFactor ?? 1.0;
        const mode = metadata.outputMode === 'redistort' ? 'Distort' : (metadata.outputMode === 'stmap' ? 'STMap' : 'Undistort');

        const scriptLines = [
            '# Foundry Nuke LensDistortion Script Snippet',
            '# Generated by Scratchbox IDE VFX Lens Engine',
            '',
            'set cut_paste_input [stack 0]',
            'version 15.0 v1',
            'push $cut_paste_input',
            'LensDistortion2 {',
            ' distortionModel "Brown-Conrady"',
            ` k1 ${params.k1.toFixed(8)}`,
            ` k2 ${params.k2.toFixed(8)}`,
            ...(params.k3 !== undefined ? [` k3 ${params.k3.toFixed(8)}`] : []),
            ` p1 ${(params.p1 ?? 0.0).toFixed(8)}`,
            ` p2 ${(params.p2 ?? 0.0).toFixed(8)}`,
            ` centre {${oc[0].toFixed(6)} ${oc[1].toFixed(6)}}`,
            ` anamorphicSqueeze ${squeeze.toFixed(4)}`,
            ` output "${mode}"`,
            ' name LensDistortion_Scratchbox_VFX',
            ' selected true',
            ' xpos 0',
            ' ypos 0',
            '}',
            '',
            '# Python Script for Nuke Script Editor / Automation API',
            '"""',
            'import nuke',
            'ld = nuke.createNode("LensDistortion2")',
            'ld["distortionModel"].setValue("Brown-Conrady")',
            `ld["k1"].setValue(${params.k1})`,
            `ld["k2"].setValue(${params.k2})`,
            `ld["p1"].setValue(${params.p1 ?? 0.0})`,
            `ld["p2"].setValue(${params.p2 ?? 0.0})`,
            `ld["centre"].setValue([${oc[0]}, ${oc[1]}])`,
            `ld["anamorphicSqueeze"].setValue(${squeeze})`,
            `ld["output"].setValue("${mode}")`,
            '"""'
        ];

        return scriptLines.join('\n') + '\n';
    }

    /**
     * Exports a standardized OpenCV camera intrinsic matrix K and distortion vector D.
     */
    public static exportOpenCvCameraMatrix(
        params: LensDistortionParams,
        width: number = 1920,
        height: number = 1080,
        focalLengthMm?: number,
        sensorWidthMm?: number
    ): OpenCvCameraCalibration {
        const focal = params.focalLengthMm ?? focalLengthMm ?? 35.0;
        const sensorW = params.sensorWidthMm ?? sensorWidthMm ?? 36.0;
        const sensorH = params.sensorHeightMm ?? (sensorW * (height / width));
        const squeeze = params.anamorphicSqueeze ?? params.squeezeFactor ?? 1.0;
        const oc = params.opticalCenter ?? [0.5, 0.5];

        const fx = (focal / sensorW) * width;
        const fy = ((focal / sensorH) * height) / squeeze;
        const cx = oc[0] * width;
        const cy = oc[1] * height;

        const distortionCoefficients = [
            params.k1,
            params.k2,
            params.p1 ?? 0.0,
            params.p2 ?? 0.0,
            params.k3 ?? 0.0,
            params.k4 ?? 0.0,
            0.0, // k5
            0.0  // k6
        ];

        return {
            imageWidth: width,
            imageHeight: height,
            cameraMatrix: [
                [fx, 0.0, cx],
                [0.0, fy, cy],
                [0.0, 0.0, 1.0]
            ],
            distortionCoefficients,
            focalLengthPx: [fx, fy],
            principalPointPx: [cx, cy],
            model: params.model ?? 'brown_conrady'
        };
    }

    /**
     * Formats a 32-bit float ST Map buffer into a structured binary export packet.
     * Ready for streaming or writing to 32-bit float EXR / TIFF / Raw files.
     */
    public static exportSTMapRaw(
        float32Array: Float32Array,
        width: number,
        height: number,
        mode: 'undistort' | 'redistort' = 'undistort'
    ): {
        width: number;
        height: number;
        channels: number;
        mode: 'undistort' | 'redistort';
        byteLength: number;
        buffer: ArrayBuffer;
    } {
        return {
            width,
            height,
            channels: 4, // RGBA float32
            mode,
            byteLength: float32Array.byteLength,
            buffer: float32Array.buffer.slice(
                float32Array.byteOffset,
                float32Array.byteOffset + float32Array.byteLength
            ) as ArrayBuffer
        };
    }

    /**
     * Derives realistic Brown-Conrady lens distortion coefficients from optical focal length
     * and sensor format.
     */
    public static calculateBrownConradyFromFocalLength(
        focalLengthMm: number,
        sensorWidthMm: number = 36.0
    ): LensDistortionParams {
        const f = Math.max(focalLengthMm, 8.0);
        const sensorScale = 36.0 / Math.max(1.0, sensorWidthMm);

        if (f < 18.0) {
            // Ultra-wide
            const factor = (18.0 / f) * sensorScale;
            return {
                k1: -0.095 * factor,
                k2: 0.024 * factor,
                k3: -0.003 * factor,
                p1: 0.0004,
                p2: -0.0002,
                chromaticAberration: 0.0045 * factor,
                anamorphicSqueeze: 1.0,
                focalLengthMm: f,
                sensorWidthMm
            };
        } else if (f < 35.0) {
            // Wide-angle (smartphone primary range)
            const factor = ((35.0 - f) / 17.0) * sensorScale;
            return {
                k1: -0.015 - 0.035 * factor,
                k2: 0.002 + 0.008 * factor,
                p1: 0.0,
                p2: 0.0,
                chromaticAberration: 0.0008 + 0.0018 * factor,
                anamorphicSqueeze: 1.0,
                focalLengthMm: f,
                sensorWidthMm
            };
        } else if (f <= 60.0) {
            // Standard normal prime
            return {
                k1: -0.004,
                k2: 0.0005,
                p1: 0.0,
                p2: 0.0,
                chromaticAberration: 0.0003,
                anamorphicSqueeze: 1.0,
                focalLengthMm: f,
                sensorWidthMm
            };
        } else {
            // Telephoto (pincushion)
            const factor = Math.min((f - 60.0) / 140.0, 1.5);
            return {
                k1: 0.004 + 0.008 * factor,
                k2: 0.0008 + 0.0015 * factor,
                p1: 0.0,
                p2: 0.0,
                chromaticAberration: 0.0002,
                anamorphicSqueeze: 1.0,
                focalLengthMm: f,
                sensorWidthMm
            };
        }
    }
}
