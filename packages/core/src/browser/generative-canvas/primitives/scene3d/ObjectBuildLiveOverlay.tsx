/**
 * What the viewport shows over an object build that is still running (common/object-build-live.ts): while only the
 * internal reference exists, the reference itself in the middle of the studio; once a pass is built and the scene
 * shows it, the reference shrinks to a card bottom-left beside the build's status. The reference is labelled generated
 * (an image model drew it), or with its own caption (an object cut out of a real photo). Nothing is drawn when the scene
 * is finished.
 */

import * as React from 'react';
import type { ObjectBuildLive } from '../../../../common/object-build-live';

function useElapsedSeconds(startedAtMs: number | undefined): number {
    const [now, setNow] = React.useState(() => Date.now());
    React.useEffect(() => {
        if (startedAtMs === undefined) return;
        const t = setInterval(() => setNow(Date.now()), 1000);
        return () => clearInterval(t);
    }, [startedAtMs]);
    return startedAtMs === undefined ? 0 : Math.max(0, Math.round((now - startedAtMs) / 1000));
}

export const ObjectBuildLiveOverlay: React.FC<{ live: ObjectBuildLive | undefined; bottomInsetPx?: number }> = ({ live, bottomInsetPx = 16 }) => {
    const elapsed = useElapsedSeconds(live?.startedAtMs);
    if (!live) return null;
    const centred = live.status === 'reference';
    const status = (
        <div style={{ display: 'flex', alignItems: 'center', gap: 8, fontSize: 12, color: '#e4e4e7' }}>
            <span className="animate-pulse" style={{ width: 8, height: 8, borderRadius: 4, background: '#60a5fa', flex: 'none' }} />
            <span>{live.message}</span>
            <span style={{ color: '#a1a1aa', fontVariantNumeric: 'tabular-nums' }}>{elapsed}s</span>
        </div>
    );
    const caption = <div style={{ fontSize: 11, color: '#a1a1aa', marginTop: 4 }}>{live.referenceCaption ?? 'Internal reference · generated by an image model'}</div>;
    return (
        <div aria-live="polite" className="sb-object-build-live" style={{ position: 'absolute', inset: 0, pointerEvents: 'none', zIndex: 25 }}>
            {centred && live.referenceUri ? (
                <div style={{ position: 'absolute', inset: 0, display: 'flex', flexDirection: 'column', alignItems: 'center', justifyContent: 'center', gap: 10 }}>
                    <div style={{ padding: 8, borderRadius: 10, background: 'rgba(18, 18, 22, 0.78)', border: '1px solid rgba(255,255,255,0.1)', boxShadow: '0 12px 32px rgba(0,0,0,0.35)' }}>
                        <img src={live.referenceUri} alt="The reference the object is being built from" style={{ display: 'block', maxHeight: '48vh', maxWidth: '42vw', borderRadius: 6 }} />
                        {caption}
                    </div>
                    <div style={{ padding: '6px 12px', borderRadius: 8, background: 'rgba(18, 18, 22, 0.78)' }}>{status}</div>
                </div>
            ) : (
                <div style={{ position: 'absolute', left: 64, bottom: bottomInsetPx, display: 'flex', alignItems: 'flex-end', gap: 10, padding: 8, borderRadius: 10, background: 'rgba(18, 18, 22, 0.78)', border: '1px solid rgba(255,255,255,0.1)' }}>
                    {live.referenceUri && (
                        <div>
                            <img src={live.referenceUri} alt="The reference the object is being built from" style={{ display: 'block', width: 132, borderRadius: 6 }} />
                            {caption}
                        </div>
                    )}
                    <div style={{ paddingBottom: 2 }}>{status}</div>
                </div>
            )}
        </div>
    );
};
