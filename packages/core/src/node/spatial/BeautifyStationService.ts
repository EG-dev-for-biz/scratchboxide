/** A station image and the model that produced it. */
export interface StationImageAnswer {
    png: Buffer;
    /** The image model that produced the picture. */
    modelUsed: string;
    /** Which model answered and, when it was not the requested one, why (see describeModelUsed). */
    modelNote?: string;
}

/**
 * Pluggable image model. The default implementation (createGoogleStationImageGenerator) uses Nano Banana / Gemini
 * image and answers with the model that produced each picture. A generator that answers with a bare PNG names no
 * model; results then say so instead of naming one.
 */
export interface StationImageGenerator {
    name: string;
    fidelity?: 'draft' | 'production';
    generate(args: {
        prompt: string;
        blockoutPng: Buffer;
        referencePng?: Buffer;     // previous accepted station warped into this pose (chained mode)
        maskPng?: Buffer;          // white = disocclusion (fill), black = keep from reference
        aspectRatio: string;       // e.g. '16:9'
        width: number; height: number;
        /** Output size the caller needs (a character sheet asks for '4K'); a generator without sizes ignores it. */
        imageSize?: '1K' | '2K' | '4K';
        /** The caller's Stop: a generator should end its model call with an AbortError when it fires. */
        signal?: AbortSignal;
    }): Promise<Buffer | StationImageAnswer>;
}

/** A generator's answer as { png, modelUsed? }: a bare PNG names no model. */
export function toStationImageAnswer(out: Buffer | StationImageAnswer): { png: Buffer; modelUsed?: string; modelNote?: string } {
    return Buffer.isBuffer(out) ? { png: out } : out;
}

/** "Images by <model>." or, when the generator named no model, "Images by the <name> generator (no model named)." */
export function describeStationImageSource(result: { modelUsed?: string; modelNote?: string; generator: string }): string {
    if (result.modelNote) return result.modelNote;
    return result.modelUsed
        ? `Generated with ${result.modelUsed}.`
        : `Generated by the ${result.generator} generator, which names no model.`;
}

