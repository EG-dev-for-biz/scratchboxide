export interface CameraUsdParameters {
    position: [number, number, number];
    target: [number, number, number];
    fovDeg?: number;
    focalLengthMm?: number;
    sensorWidthMm?: number;
    sensorHeightMm?: number;
    nearClipMeters?: number;
    farClipMeters?: number;
}

export interface UsdExportOptions {
    outputPath?: string;
    assetName?: string;
    camera?: CameraUsdParameters;
    exportMaterialX?: boolean;
    materialName?: string;
    stoneType?: StoneType | string;
    roughness?: number;
    delightUniforms?: {
        uShadowLift?: number;
        uHighlightCompress?: number;
    };
}

export interface UsdExportResult {
    success: boolean;
    usdaFilePath?: string;
    mtlxFilePath?: string;
    usdaContent: string;
    mtlxContent?: string;
}

export interface MaterialXExportOptions {
    materialName?: string;
    stoneType?: StoneType | string;
    roughness?: number;
    delightUniforms?: {
        uShadowLift?: number;
        uHighlightCompress?: number;
    };
}

export interface MatchLightingReferenceOptions {
    imagePath: string;
    landmarkName?: string;
    geodeticCoords?: { lat: number; lng: number };
    timestampIso?: string;
    cameraHeadingDeg?: number;
    cameraPitchDeg?: number;
    cameraPosition?: [number, number, number];
    cameraTarget?: [number, number, number];
    fovDeg?: number;
    stoneType?: StoneType | string;
    autoExportUsd?: boolean;
    outputUsdPath?: string;
}

export interface MatchLightingReferenceResult {
    success: boolean;
    rig: PhotometricLightingRigData;
    threeJsUniforms: {
        uSunDirection: [number, number, number];
        uSunColor: [number, number, number];
        uSkyColor: [number, number, number];
        uGroundColor: [number, number, number];
        uSunIntensity: number;
        uAmbientIntensity: number;
        uShadowLift: number;
        uHighlightCompress: number;
    };
    usdExportPath?: string;
    mtlxExportPath?: string;
    summary: string;
}

export class PhotometricUsdBridgeService {

    /**
     * Generates a complete OpenUSD document in ASCII (.usda) conforming to UsdLux schemas.
     */
    public static generateUsda(rig: PhotometricLightingRigData, options: UsdExportOptions = {}): string {
        const assetName = (options.assetName || rig.name || 'Scene').replace(/[^a-zA-Z0-9_]/g, '_');
        const camera = options.camera;

        let usda = `#usda 1.0
(
    defaultPrim = "${assetName}"
    metersPerUnit = 1.0
    upAxis = "Y"
    doc = "Generated by Scratchbox IDE Professional Photometric OpenUSD Exporter"
)

def "${assetName}" (
    kind = "assembly"
)
{
    def "World"
    {
        def "Lights"
        {
`;

        for (const light of rig.lights) {
            const lightPrimName = light.id.replace(/[^a-zA-Z0-9_]/g, '_');
            const pos = light.position || [0, 10, 0];
            const rgb = light.colorLinearRgb || [1, 1, 1];
            const kelvin = light.cctKelvin || 5600;
            const intensity = light.intensityLux || 1000.0;

            if (light.type === 'directional') {
                const dir = light.direction || [-0.3, -0.7, -0.6];
                // Directional / Sun Light -> UsdLuxDistantLight
                usda += `            def UsdLuxDistantLight "${lightPrimName}"
            {
                float inputs:angle = 0.53
                color3f inputs:color = (${rgb[0].toFixed(4)}, ${rgb[1].toFixed(4)}, ${rgb[2].toFixed(4)})
                float inputs:colorTemperature = ${kelvin.toFixed(1)}
                bool inputs:enableColorTemperature = 1
                float inputs:intensity = ${intensity.toFixed(1)}
                bool inputs:normalize = 1
                float inputs:exposure = 0
                double3 xformOp:translate = (${pos[0].toFixed(3)}, ${pos[1].toFixed(3)}, ${pos[2].toFixed(3)})
                uniform token[] xformOpOrder = ["xformOp:translate"]
            }
`;
            } else if (light.type === 'area_rect') {
                // Area Light -> UsdLuxRectLight
                usda += `            def UsdLuxRectLight "${lightPrimName}"
            {
                float inputs:width = 2.0
                float inputs:height = 2.0
                color3f inputs:color = (${rgb[0].toFixed(4)}, ${rgb[1].toFixed(4)}, ${rgb[2].toFixed(4)})
                float inputs:colorTemperature = ${kelvin.toFixed(1)}
                bool inputs:enableColorTemperature = 1
                float inputs:intensity = ${intensity.toFixed(1)}
                float inputs:exposure = ${light.exposureStopsDelta ? light.exposureStopsDelta.toFixed(2) : 0}
                double3 xformOp:translate = (${pos[0].toFixed(3)}, ${pos[1].toFixed(3)}, ${pos[2].toFixed(3)})
                uniform token[] xformOpOrder = ["xformOp:translate"]
            }
`;
            } else if (light.type === 'spot') {
                // Spot Light -> UsdLuxSphereLight with shaping cone
                const innerCone = light.beamInnerConeRad ? (light.beamInnerConeRad * 180 / Math.PI) : 30;
                const outerCone = light.beamOuterConeRad ? (light.beamOuterConeRad * 180 / Math.PI) : 45;
                usda += `            def UsdLuxSphereLight "${lightPrimName}"
            {
                float inputs:radius = 0.25
                color3f inputs:color = (${rgb[0].toFixed(4)}, ${rgb[1].toFixed(4)}, ${rgb[2].toFixed(4)})
                float inputs:colorTemperature = ${kelvin.toFixed(1)}
                bool inputs:enableColorTemperature = 1
                float inputs:intensity = ${intensity.toFixed(1)}
                float inputs:shaping:cone:angle = ${outerCone.toFixed(1)}
                float inputs:shaping:cone:softness = ${Math.max(0, outerCone - innerCone).toFixed(1)}
                double3 xformOp:translate = (${pos[0].toFixed(3)}, ${pos[1].toFixed(3)}, ${pos[2].toFixed(3)})
                uniform token[] xformOpOrder = ["xformOp:translate"]
            }
`;
            } else {
                // Point / Practical -> UsdLuxSphereLight
                usda += `            def UsdLuxSphereLight "${lightPrimName}"
            {
                float inputs:radius = 0.15
                color3f inputs:color = (${rgb[0].toFixed(4)}, ${rgb[1].toFixed(4)}, ${rgb[2].toFixed(4)})
                float inputs:colorTemperature = ${kelvin.toFixed(1)}
                bool inputs:enableColorTemperature = 1
                float inputs:intensity = ${intensity.toFixed(1)}
                double3 xformOp:translate = (${pos[0].toFixed(3)}, ${pos[1].toFixed(3)}, ${pos[2].toFixed(3)})
                uniform token[] xformOpOrder = ["xformOp:translate"]
            }
`;
            }
        }

        // Sky Environment Dome Light
        usda += `            def UsdLuxDomeLight "SkyDomeLight"
            {
                color3f inputs:color = (0.75, 0.85, 1.0)
                float inputs:colorTemperature = 7500
                bool inputs:enableColorTemperature = 1
                float inputs:intensity = 1.0
                float inputs:exposure = 0.0
            }
        }
`;

        // Resected 6-DOF Camera Definition
        if (camera) {
            const camPos = camera.position || [0, 5, 20];
            const camTarget = camera.target || [0, 5, 0];
            const focalLength = camera.focalLengthMm || 28.0;
            const horizAperture = camera.sensorWidthMm || 36.0;
            const vertAperture = camera.sensorHeightMm || 24.0;
            const nearClip = camera.nearClipMeters || 0.1;
            const farClip = camera.farClipMeters || 10000.0;

            usda += `        def Camera "ResectedCamera"
        {
            float2 clippingRange = (${nearClip}, ${farClip})
            float focalLength = ${focalLength.toFixed(1)}
            float horizontalAperture = ${horizAperture.toFixed(1)}
            float verticalAperture = ${vertAperture.toFixed(1)}
            double3 xformOp:translate = (${camPos[0].toFixed(3)}, ${camPos[1].toFixed(3)}, ${camPos[2].toFixed(3)})
            uniform token[] xformOpOrder = ["xformOp:translate"]
        }
`;
        }

        usda += `    }
}
`;
        return usda;
    }

    /**
     * Generates a MaterialX document (.mtlx) conforming to OpenPBR / Standard Surface specs.
     */
    public static generateMaterialX(options: MaterialXExportOptions = {}): string {
        const matName = options.materialName || 'CalibratedStone';
        const stoneType = (options.stoneType || 'travertine').toLowerCase();
        let baseR = 0.86, baseG = 0.82, baseB = 0.78; // Roman travertine neutral default
        if (stoneType.includes('limestone')) {
            baseR = 0.90; baseG = 0.88; baseB = 0.82;
        } else if (stoneType.includes('sandstone')) {
            baseR = 0.88; baseG = 0.76; baseB = 0.62;
        } else if (stoneType.includes('granite')) {
            baseR = 0.75; baseG = 0.74; baseB = 0.73;
        } else if (stoneType.includes('brick')) {
            baseR = 0.72; baseG = 0.42; baseB = 0.32;
        }
        const roughness = options.roughness !== undefined ? options.roughness : 0.82;

        return `<?xml version="1.0"?>
<materialx version="1.38">
  <!-- MaterialX Physical Shader calibrated to Real-World Reference -->
  <standard_surface name="${matName}_surface" type="surfaceshader">
    <input name="base" type="float" value="1.0" />
    <input name="base_color" type="color3" value="${baseR.toFixed(3)}, ${baseG.toFixed(3)}, ${baseB.toFixed(3)}" />
    <input name="diffuse_roughness" type="float" value="${roughness.toFixed(3)}" />
    <input name="specular" type="float" value="0.25" />
    <input name="specular_roughness" type="float" value="${roughness.toFixed(3)}" />
    <input name="specular_IOR" type="float" value="1.54" />
  </standard_surface>

  <surfacematerial name="${matName}" type="material">
    <input name="surfaceshader" type="surfaceshader" nodename="${matName}_surface" />
  </surfacematerial>
</materialx>
`;
    }

    /**
     * Exports rig and material definitions to disk.
     */
    public static exportToUsd(rig: PhotometricLightingRigData, options: UsdExportOptions = {}): UsdExportResult {
        const usdaContent = this.generateUsda(rig, options);
        let usdaFilePath = options.outputPath;
        let mtlxFilePath: string | undefined = undefined;
        let mtlxContent: string | undefined = undefined;

        if (usdaFilePath) {
            const dir = path.dirname(usdaFilePath);
            fs.mkdirSync(dir, { recursive: true });
            fs.writeFileSync(usdaFilePath, usdaContent, 'utf8');

            if (options.exportMaterialX) {
                mtlxContent = this.generateMaterialX({
                    materialName: options.materialName,
                    stoneType: options.stoneType,
                    roughness: options.roughness,
                    delightUniforms: options.delightUniforms
                });
                const parsed = path.parse(usdaFilePath);
                mtlxFilePath = path.join(parsed.dir, `${parsed.name}.mtlx`);
                fs.writeFileSync(mtlxFilePath, mtlxContent, 'utf8');
            }
        }

        return {
            success: true,
            usdaFilePath,
            mtlxFilePath,
            usdaContent,
            mtlxContent
        };
    }
}

/**
 * High-level orchestration function to inversely solve lighting from an image
 * reference and construct matching physical lights, Three.js shader uniforms, and OpenUSD exports.
 */
export async function matchLightingToReference(
    options: MatchLightingReferenceOptions
): Promise<MatchLightingReferenceResult> {
    if (!options.imagePath || !fs.existsSync(options.imagePath)) {
        throw new Error(`matchLightingToReference: Image file not found at '${options.imagePath}'.`);
    }

    // 1. Inverse photometric analysis on reference photograph
    const est = await InverseLightingEstimatorService.estimateFromImage({
        imagePath: options.imagePath,
        hfovDeg: options.fovDeg || 60,
        vfovDeg: (options.fovDeg || 60) * 0.75,
        cameraHeadingDeg: options.cameraHeadingDeg || 0,
        cameraPitchDeg: options.cameraPitchDeg || 0
    });

    // 2. Solar Ephemeris fallback / refinement if coordinates & date supplied
    let keyAzimuth = est.keyLight.azimuthDeg;
    let keyElevation = est.keyLight.elevationDeg;
    let keyKelvin = est.keyLight.cctKelvin;

    if (options.geodeticCoords && options.timestampIso) {
        try {
            const date = new Date(options.timestampIso);
            const solar = calculateNOAASolarPosition(
                date,
                options.geodeticCoords.lat,
                options.geodeticCoords.lng
            );
            if (solar && solar.elevationDeg > 0) {
                keyAzimuth = solar.azimuthDeg;
                keyElevation = solar.elevationDeg;
            }
        } catch (e) {}
    }

    // 3. Assemble balanced photographic lighting rig via Gaffer Service
    const rig = LightingGafferService.buildGafferRig('three_point', {
        keyToFillRatio: stopsToRatio(Math.abs(est.fillLight.exposureStopsDelta || 2.0)),
        keyKelvin: keyKelvin,
        fillKelvin: est.fillLight.cctKelvin,
        penumbraSoftness: 1.0 - est.shadowSharpness
    });

    // Update rig key light position from solved spherical angles
    const key = rig.lights.find(l => l.role === 'key');
    if (key) {
        const azRad = keyAzimuth * Math.PI / 180.0;
        const elRad = keyElevation * Math.PI / 180.0;
        const dist = 100.0;
        key.position = [
            Math.sin(azRad) * Math.cos(elRad) * dist,
            Math.sin(elRad) * dist,
            Math.cos(azRad) * Math.cos(elRad) * dist
        ];
        key.direction = [
            -Math.sin(azRad) * Math.cos(elRad),
            -Math.sin(elRad),
            -Math.cos(azRad) * Math.cos(elRad)
        ];
        key.cctKelvin = keyKelvin;
        const rgb = planckianKelvinToRgb(keyKelvin);
        key.colorLinearRgb = [rgb.r, rgb.g, rgb.b];
        key.intensityLux = est.keyLight.intensityLux || 80000.0;
        key.penumbraSoftness = Math.max(0.1, 1.0 - est.shadowSharpness);
    }

    // 4. Synthesize Three.js uniforms for instant in-viewport illumination
    const sunRgb = planckianKelvinToRgb(keyKelvin);
    const skyRgb = planckianKelvinToRgb(est.fillLight.cctKelvin || 7500);
    const groundRgb = planckianKelvinToRgb(3200);

    const threeJsUniforms = {
        uSunDirection: (key?.direction ? [key.direction[0], key.direction[1], key.direction[2]] : [-0.3, -0.7, -0.6]) as [number, number, number],
        uSunColor: [sunRgb.r, sunRgb.g, sunRgb.b] as [number, number, number],
        uSkyColor: [skyRgb.r, skyRgb.g, skyRgb.b] as [number, number, number],
        uGroundColor: [groundRgb.r * 0.4, groundRgb.g * 0.35, groundRgb.b * 0.3] as [number, number, number],
        uSunIntensity: (key?.intensityLux || 80000) / 50000.0,
        uAmbientIntensity: 0.85,
        uShadowLift: 0.60,
        uHighlightCompress: 0.45
    };

    // 5. OpenUSD & MaterialX Export if requested
    let usdExportPath: string | undefined = undefined;
    let mtlxExportPath: string | undefined = undefined;

    if (options.autoExportUsd) {
        const outPath = options.outputUsdPath || path.join(process.cwd(), 'public/data/matched_lighting_rig.usda');
        const exportRes = PhotometricUsdBridgeService.exportToUsd(rig, {
            outputPath: outPath,
            assetName: options.landmarkName || 'ReferenceMatchedScene',
            exportMaterialX: true,
            stoneType: options.stoneType || 'travertine',
            camera: options.cameraPosition && options.cameraTarget ? {
                position: options.cameraPosition,
                target: options.cameraTarget,
                fovDeg: options.fovDeg || 54
            } : undefined
        });
        usdExportPath = exportRes.usdaFilePath;
        mtlxExportPath = exportRes.mtlxFilePath;
    }

    const summary = `Matched physical scene lighting to reference photograph '${path.basename(options.imagePath)}': Key Sun at Azimuth ${keyAzimuth.toFixed(1)}°, Elevation ${keyElevation.toFixed(1)}° (${keyKelvin}K), Fill Ambient at ${est.fillLight.cctKelvin}K (${(1.0 - est.shadowSharpness).toFixed(2)} penumbra diffusion). OpenUSD export: ${usdExportPath ? path.basename(usdExportPath) : 'Disabled'}.`;

    return {
        success: true,
        rig,
        threeJsUniforms,
        usdExportPath,
        mtlxExportPath,
        summary
    };
}
