// NOTICE.md

/** The generated section (markers included) for every library under root. */
export function renderNativeNotices(root: string = nativeThirdPartyRoot()): string {
    const libs = readVendoredLibraries(root);
    const out: string[] = [
        NOTICE_BEGIN,
        '',
        '## Native third-party code',
        '',
        'The native 3D engine includes the following third-party code, vendored under',
        '`packages/core/src/native/3d-engine/third_party/` (each folder\'s VENDORED.md lists the files taken and every local change).',
        ''
    ];
    if (!libs.length) out.push('None.', '');
    for (const lib of libs) {
        const licence = fs.readFileSync(path.join(lib.dir, lib.license), 'utf8').replace(/\r\n/g, '\n').trimEnd();
        out.push(
            `### ${lib.name} (${lib.version})`,
            '',
            `* License: ${lib.spdx}`,
            `* Project: ${lib.upstream}`,
            `* Source: commit ${lib.commit}, vendored ${lib.vendored}`,
            `* ${lib.copyright}`,
            `* Local changes: ${lib.unmodified ? 'none' : `yes, listed in third_party/${lib.name}/VENDORED.md`}`,
            '',
            '```text',
            licence,
            '```',
            ''
        );
    }
    out.push(NOTICE_END);
    return out.join('\n');
}

/** noticeText with its generated section replaced by `section` (appended when it has none). */
export function applyNativeNotices(noticeText: string, section: string): string {
    const begin = noticeText.indexOf(NOTICE_BEGIN.slice(0, 40));
    const endMarker = noticeText.indexOf(NOTICE_END);
    if (begin >= 0 && endMarker > begin) {
        return noticeText.slice(0, begin) + section + noticeText.slice(endMarker + NOTICE_END.length);
    }
    return `${noticeText.trimEnd()}\n\n${section}\n`;
}

