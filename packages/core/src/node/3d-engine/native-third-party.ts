// Building a library

export interface VendoredLibraryBuild {
    name: string;
    /** The static archive (ar format), to put in a NativeCompileSpec's libs. */
    archivePath: string;
    key: string;
    cacheHit: boolean;
    compileMs: number;
    objectCount: number;
}

export interface VendoredBuildOptions {
    /** Third-party root (default nativeThirdPartyRoot()). */
    root?: string;
    /** Cache root (default nativeBuildCacheRoot()). */
    cacheRoot?: string;
    /** C++ compiler command (default $CXX or clang++); C sources go through the same driver with -x c. */
    compiler?: string;
    /** Archiver (default $AR or ar). */
    archiver?: string;
    timeoutMs?: number;
}

const ARCHIVE_KEY_FORMAT = 'scratchbox-vendored-archive-v1';

/** The SDK sysroot on macOS, as compileSource passes it, so library and program see the same headers. */
export function darwinSysrootFlags(): string[] {
    if (process.platform !== 'darwin') return [];
    const macSdk = '/Library/Developer/CommandLineTools/SDKs/MacOSX.sdk';
    return fs.existsSync(macSdk) ? ['-isysroot', macSdk] : [];
}

/** The flags a source of lib is compiled with: the engine's (C++20 or C11, -O3, -march=native only on request) plus its cflags. */
export function vendoredSourceFlags(lib: VendoredLibrary, file: string): string[] {
    const isC = /\.c$/.test(file);
    const base = defaultNativeFlags().map(f => (isC && f === '-std=c++20' ? '-std=c11' : f));
    return [...(isC ? ['-x', 'c'] : []), ...base, ...darwinSysrootFlags(), ...lib.cflags];
}

function compilerWords(compiler?: string): string[] {
    const words = (compiler || process.env.CXX || 'clang++').trim().split(/\s+/).filter(Boolean);
    return words.length ? words : ['clang++'];
}

function run(argv: string[], timeoutMs: number): Promise<string> {
    return new Promise((resolve, reject) => {
        execFile(argv[0], argv.slice(1), { timeout: timeoutMs, maxBuffer: 64 * 1024 * 1024, windowsHide: true }, (err, stdout, stderr) => {
            const output = `${String(stderr || '')}${stdout ? `\n${String(stdout)}` : ''}`.trim();
            if (err) reject(new NativeBuildError(output || err.message, output || err.message));
            else resolve(output);
        });
    });
}

async function mapLimit<T, R>(items: T[], limit: number, fn: (t: T, i: number) => Promise<R>): Promise<R[]> {
    const out = new Array<R>(items.length);
    let next = 0;
    await Promise.all(Array.from({ length: Math.min(limit, items.length) }, async () => {
        while (next < items.length) {
            const i = next++;
            out[i] = await fn(items[i], i);
        }
    }));
    return out;
}

/** The archive's cache key: every source's include closure, its flags, the compiler and the platform. */
export function vendoredArchiveKey(lib: VendoredLibrary, sources: string[], compiler?: string): string {
    const hasher = crypto.createHash('sha256')
        .update(`${ARCHIVE_KEY_FORMAT}\n${lib.name}\n${process.platform}/${process.arch}\n`)
        .update(`compiler=${compilerIdentity(compiler)}\n`);
    for (const src of sources) {
        const flags = vendoredSourceFlags(lib, src);
        hasher.update(`${path.relative(lib.dir, src)}\nflags=${JSON.stringify(flags)}\n${hashIncludeClosure({ file: src }, [path.dirname(lib.dir)]).hash}\n`);
        if (flags.some(f => /^-m(arch|cpu|tune)=native/.test(f))) hasher.update(`cpu=${os.cpus()[0]?.model ?? 'unknown'}\n`);
    }
    return `lib-${hasher.digest('hex').slice(0, 36)}`;
}

const archivesInFlight = new Map<string, Promise<VendoredLibraryBuild>>();

/**
 * Compiles a vendored library's sources into a static archive in the native build cache (once per key across
 * processes, under the cache's lock) and returns its path. A failed compile throws NativeBuildError with the
 * compiler's output; nothing older is used instead. A header-only library (no sources) throws: there is nothing to link.
 */
export async function buildVendoredLibrary(name: string, options: VendoredBuildOptions = {}): Promise<VendoredLibraryBuild> {
    const started = Date.now();
    const root = options.root ?? nativeThirdPartyRoot();
    const lib = readVendoredLibrary(path.join(root, name));
    const sources = vendoredSources(lib);
    if (!sources.length) throw new NativeBuildError(`${name} has no sources to build (header-only: include it, do not link it)`, '');
    const key = vendoredArchiveKey(lib, sources, options.compiler);
    const cacheRoot = options.cacheRoot ?? nativeBuildCacheRoot();
    const entryDir = path.join(cacheRoot, key);
    const archivePath = nativeBuildEntryBinary(cacheRoot, key);
    const hit = (): VendoredLibraryBuild => ({ name, archivePath, key, cacheHit: true, compileMs: Date.now() - started, objectCount: sources.length });
    if (fs.existsSync(archivePath) && markNativeBuildEntryUsed(entryDir) && fs.existsSync(archivePath)) return hit();
    const pending = archivesInFlight.get(archivePath);
    if (pending) return pending;
    const build = (async (): Promise<VendoredLibraryBuild> => {
        const timeoutMs = options.timeoutMs ?? 15 * 60_000;
        fs.mkdirSync(entryDir, { recursive: true });
        const release = await acquireBuildLock(`${archivePath}.lock`, timeoutMs);
        try {
            if (fs.existsSync(archivePath)) { markNativeBuildEntryUsed(entryDir); return hit(); }
            removeOrphanedTemps(archivePath);
            const tag = `${process.pid}-${crypto.randomBytes(4).toString('hex')}`;
            const objDir = `${archivePath}.tmp-${tag}.d`;
            const tmpArchive = `${archivePath}.tmp-${tag}.a`;
            fs.mkdirSync(objDir, { recursive: true });
            const compileStart = Date.now();
            try {
                const cc = compilerWords(options.compiler);
                const jobs = Math.max(1, Math.min(8, Math.floor(os.cpus().length / 2)));
                const objects = await mapLimit(sources, jobs, async (src, i) => {
                    const obj = path.join(objDir, `${i}_${path.basename(src).replace(/\.\w+$/, '')}.o`);
                    await run([...cc, ...vendoredSourceFlags(lib, src), '-c', src, '-o', obj], timeoutMs);
                    return obj;
                });
                await run([options.archiver || process.env.AR || 'ar', 'rcs', tmpArchive, ...objects], timeoutMs);
                fs.renameSync(tmpArchive, archivePath);
                markNativeBuildEntryUsed(entryDir);
                return { name, archivePath, key, cacheHit: false, compileMs: Date.now() - compileStart, objectCount: objects.length };
            } catch (err) {
                throw err instanceof NativeBuildError
                    ? new NativeBuildError(`could not build vendored ${name}: ${err.compilerOutput.slice(-4000)}`, err.compilerOutput)
                    : err;
            } finally {
                fs.rmSync(objDir, { recursive: true, force: true });
                fs.rmSync(tmpArchive, { force: true });
            }
        } finally {
            release();
        }
    })();
    archivesInFlight.set(archivePath, build);
    let result: VendoredLibraryBuild;
    try {
        result = await build;
    } finally {
        archivesInFlight.delete(archivePath);
    }
    if (!result.cacheHit) maybePruneNativeBuildCache(cacheRoot);
    return result;
}

/** Builds each named library and returns their archives, in order, for a NativeCompileSpec's libs. */
export async function vendoredLibraryArchives(names: string[], options: VendoredBuildOptions = {}): Promise<string[]> {
    const builds = await Promise.all(names.map(n => buildVendoredLibrary(n, options)));
    return builds.map(b => b.archivePath);
}
