/**
 * Vendored third-party code in the native engine (`packages/core/src/native/3d-engine/third_party/`; the convention
 * is its README.md).
 *
 * - readVendoredLibraries: each library's VENDORED.md front matter.
 * - checkThirdPartyLicences: the licence gate (allowed SPDX ids only; no GPL-family or non-commercial text anywhere;
 *   every library licensed; MPL only unmodified).
 * - renderNativeNotices / applyNativeNotices: the generated "Native third-party code" section of the root NOTICE.md
 *   (`npm run notices:native`).
 * - buildVendoredLibrary: a library's sources compiled once into a static archive in the native build cache, keyed
 *   on the content of every source and every header they include, the flags and the compiler.
 */

import { execFile } from 'child_process';
import * as crypto from 'crypto';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import {
    acquireBuildLock, compilerIdentity, defaultNativeFlags, hashIncludeClosure, markNativeBuildEntryUsed,
    maybePruneNativeBuildCache, nativeBuildCacheRoot, nativeBuildEntryBinary, NativeBuildError, removeOrphanedTemps
} from './native-build-cache';

/** SPDX ids a vendored library may carry. MPL-2.0 only for files taken unchanged. */
export const ALLOWED_SPDX = ['MIT', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', 'Zlib', 'BSL-1.0', 'ISC', 'MPL-2.0'] as const;
const ALLOWED_SPDX_EXCEPTIONS = ['LLVM-exception'];

const NOTICE_BEGIN = '<!-- BEGIN native-third-party: generated by `npm run notices:native` from packages/core/src/native/3d-engine/third_party; do not edit by hand -->';
const NOTICE_END = '<!-- END native-third-party -->';

// ============================================================================================
// Where

function findUp(candidates: string[]): string | undefined {
    return candidates.find(p => fs.existsSync(p));
}

/** `packages/core/src/native/3d-engine/third_party`, found from the package, the runtime location or the working directory. */
export function nativeThirdPartyRoot(): string {
    let fromPackageJson: string | undefined;
    try {
        fromPackageJson = path.resolve(path.dirname(require.resolve('@scratchbox/core/package.json')), 'src/native/3d-engine/third_party');
    } catch {
        // fall back
    }
    const candidates = [
        fromPackageJson,
        path.resolve(__dirname, '../../native/3d-engine/third_party'),
        path.resolve(__dirname, '../../../src/native/3d-engine/third_party'),
        path.resolve(process.cwd(), 'packages/core/src/native/3d-engine/third_party'),
        path.resolve(process.cwd(), '../packages/core/src/native/3d-engine/third_party')
    ].filter((p): p is string => Boolean(p));
    return findUp(candidates) ?? candidates[0];
}

// ============================================================================================
// VENDORED.md

export interface VendoredLibrary {
    /** The folder name. */
    name: string;
    dir: string;
    upstream: string;
    version: string;
    commit: string;
    vendored: string;
    spdx: string;
    /** The licence file, relative to dir. */
    license: string;
    copyright: string;
    /** Globs (relative to dir) of the sources the builder compiles; empty for a header-only library. */
    sources: string[];
    /** Extra flags for this library's own sources. */
    cflags: string[];
    /** The "Local changes" section's text ('' when there is none). */
    localChanges: string;
    /** True when "Local changes" says None. */
    unmodified: boolean;
}

const REQUIRED_FIELDS = ['name', 'upstream', 'version', 'commit', 'vendored', 'spdx', 'license', 'copyright'] as const;

/** The `key: value` lines between the leading `---` fences (a trailing ` # comment` is dropped). */
export function parseFrontMatter(text: string): Record<string, string> {
    const m = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/.exec(text);
    if (!m) return {};
    const out: Record<string, string> = {};
    for (const line of m[1].split(/\r?\n/)) {
        const kv = /^([A-Za-z_][\w-]*):[ \t]*(.*)$/.exec(line);
        if (!kv) continue;
        out[kv[1]] = kv[2].replace(/\s+#\s.*$/, '').trim();
    }
    return out;
}

function markdownSection(text: string, heading: string): string {
    const lines = text.split(/\r?\n/);
    const start = lines.findIndex(l => new RegExp(`^##\\s+${heading}\\s*$`, 'i').test(l));
    if (start < 0) return '';
    const end = lines.findIndex((l, i) => i > start && /^##\s/.test(l));
    return lines.slice(start + 1, end < 0 ? undefined : end).join('\n').trim();
}

/** Parses one library's VENDORED.md; throws naming what is missing. */
export function readVendoredLibrary(dir: string): VendoredLibrary {
    const file = path.join(dir, 'VENDORED.md');
    if (!fs.existsSync(file)) throw new Error(`${path.basename(dir)}: no VENDORED.md`);
    const text = fs.readFileSync(file, 'utf8');
    const fm = parseFrontMatter(text);
    const missing = REQUIRED_FIELDS.filter(k => !fm[k]);
    if (missing.length) throw new Error(`${path.basename(dir)}/VENDORED.md: front matter lacks ${missing.join(', ')}`);
    if (fm.name !== path.basename(dir)) throw new Error(`${path.basename(dir)}/VENDORED.md: name "${fm.name}" is not the folder name`);
    const localChanges = markdownSection(text, 'Local changes');
    return {
        name: fm.name,
        dir,
        upstream: fm.upstream,
        version: fm.version,
        commit: fm.commit,
        vendored: fm.vendored,
        spdx: fm.spdx,
        license: fm.license,
        copyright: fm.copyright,
        sources: (fm.sources ?? '').split(/\s+/).filter(Boolean),
        cflags: (fm.cflags ?? '').split(/\s+/).filter(Boolean),
        localChanges,
        unmodified: /^none\.?$/i.test(localChanges)
    };
}

/** Every library folder under root, by name. */
export function vendoredLibraryDirs(root: string = nativeThirdPartyRoot()): string[] {
    if (!fs.existsSync(root)) return [];
    return fs.readdirSync(root, { withFileTypes: true })
        .filter(e => e.isDirectory() && !e.name.startsWith('.'))
        .map(e => path.join(root, e.name))
        .sort();
}

export function readVendoredLibraries(root: string = nativeThirdPartyRoot()): VendoredLibrary[] {
    return vendoredLibraryDirs(root).map(readVendoredLibrary);
}

function walk(dir: string): string[] {
    const out: string[] = [];
    for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
        const p = path.join(dir, e.name);
        if (e.isDirectory()) out.push(...walk(p));
        else if (e.isFile()) out.push(p);
    }
    return out;
}

function globToRegExp(glob: string): RegExp {
    let re = '';
    for (let i = 0; i < glob.length; i++) {
        const c = glob[i];
        if (c === '*' && glob[i + 1] === '*') { re += '.*'; i++; if (glob[i + 1] === '/') i++; }
        else if (c === '*') re += '[^/]*';
        else if (c === '?') re += '[^/]';
        else re += c.replace(/[.+^${}()|[\]\\]/g, '\\$&');
    }
    return new RegExp(`^${re}$`);
}

/** The library's source files (absolute, sorted) matching its `sources` globs. */
export function vendoredSources(lib: VendoredLibrary): string[] {
    const res = lib.sources.map(globToRegExp);
    return walk(lib.dir)
        .filter(f => /\.(c|cc|cpp|cxx)$/.test(f))
        .filter(f => res.some(r => r.test(path.relative(lib.dir, f).split(path.sep).join('/'))));
}

// ============================================================================================
// Licence gate

const LICENCE_TEXT: Record<string, RegExp[]> = {
    'MIT': [/Permission is hereby granted, free of charge/i],
    'Apache-2.0': [/Apache License,?\s+Version 2\.0/i],
    'BSD-2-Clause': [/Redistribution and use in source and binary forms/i],
    'BSD-3-Clause': [/Redistribution and use in source and binary forms/i, /Neither the name/i],
    'Zlib': [/provided ['‘]as-is['’]/i, /altered source versions must be plainly marked/i],
    'BSL-1.0': [/Boost Software License/i],
    'ISC': [/Permission to use, copy, modify, and\/or distribute this software for any\s+purpose/i],
    'MPL-2.0': [/Mozilla Public License,?\s+(?:v\.\s*|Version\s+)2\.0/i]
};

const FORBIDDEN_TEXT: { what: string; re: RegExp }[] = [
    { what: 'GNU GPL-family licence text', re: /GNU\s+(?:Lesser\s+|Library\s+|Affero\s+)?General\s+Public\s+Licen[cs]e/i },
    { what: 'a GPL-family licence name', re: /\b[AL]?GPL[-\s]?v?[123](?:\.\d)?\b/ },
    { what: 'a non-commercial licence', re: /non[-\s]?commercial|CC[-\s]BY(?:[-\s]SA)?[-\s]NC/i }
];

/** The ids of an SPDX expression; ids not allowed are returned in `bad`. */
export function spdxIds(expr: string): { ids: string[]; bad: string[] } {
    const tokens = expr.replace(/[()]/g, ' ').split(/\s+/).filter(Boolean);
    const ids: string[] = [];
    const bad: string[] = [];
    for (let i = 0; i < tokens.length; i++) {
        const t = tokens[i];
        if (t === 'AND' || t === 'OR') continue;
        if (t === 'WITH') {
            const ex = tokens[++i];
            if (!ex || !ALLOWED_SPDX_EXCEPTIONS.includes(ex)) bad.push(`WITH ${ex ?? '?'}`);
            continue;
        }
        const id = t.replace(/\+$/, '');
        ids.push(id);
        if (!(ALLOWED_SPDX as readonly string[]).includes(id)) bad.push(t);
    }
    if (!ids.length) bad.push('(empty)');
    return { ids, bad };
}

/**
 * The licence gate over root: one line per problem, empty when everything passes. Reads every file's SPDX lines and
 * licence text, each library's VENDORED.md and licence file. root/README.md and each VENDORED.md are ours and are
 * read only for their front matter.
 */
export function checkThirdPartyLicences(root: string = nativeThirdPartyRoot()): string[] {
    const problems: string[] = [];
    if (!fs.existsSync(root)) return [`${root}: missing`];
    for (const e of fs.readdirSync(root, { withFileTypes: true })) {
        if (e.isFile() && e.name !== 'README.md') problems.push(`${e.name}: a file outside any library folder (no licence)`);
    }
    for (const dir of vendoredLibraryDirs(root)) {
        const name = path.basename(dir);
        let lib: VendoredLibrary | undefined;
        try {
            lib = readVendoredLibrary(dir);
        } catch (err) {
            problems.push((err as Error).message);
        }
        if (lib) {
            const { ids, bad } = spdxIds(lib.spdx);
            if (bad.length) problems.push(`${name}: SPDX "${lib.spdx}" has ids not allowed: ${bad.join(', ')}`);
            const licFile = path.join(dir, lib.license);
            if (!fs.existsSync(licFile)) {
                problems.push(`${name}: licence file ${lib.license} not found`);
            } else {
                const text = fs.readFileSync(licFile, 'utf8');
                if (!ids.some(id => LICENCE_TEXT[id]?.every(re => re.test(text)))) {
                    problems.push(`${name}: ${lib.license} does not read as ${lib.spdx}`);
                }
            }
            if (ids.includes('MPL-2.0') && !lib.unmodified) problems.push(`${name}: MPL-2.0 code may only be vendored unmodified, but Local changes lists edits`);
            if (!lib.localChanges) problems.push(`${name}/VENDORED.md: no "## Local changes" section (write "None." when there are none)`);
        }
        for (const file of walk(dir)) {
            const rel = path.relative(root, file);
            if (path.basename(file) === 'VENDORED.md' && path.dirname(file) === dir) continue;
            const text = fs.readFileSync(file, 'latin1');
            for (const m of Array.from(text.matchAll(/SPDX-License-Identifier:\s*([^\n\r*]+?)\s*(?:\*\/)?\s*$/gm))) {
                const { bad } = spdxIds(m[1]);
                if (bad.length) problems.push(`${rel}: SPDX-License-Identifier ${m[1].trim()} is not allowed`);
            }
            for (const f of FORBIDDEN_TEXT) {
                const hit = f.re.exec(text);
                if (hit) problems.push(`${rel}: carries ${f.what} ("${hit[0]}")`);
            }
            if (lib && spdxIds(lib.spdx).ids.includes('MPL-2.0') && /Modified by Scratchbox/i.test(text)) {
                problems.push(`${rel}: an MPL-2.0 file was modified`);
            }
        }
    }
    return problems;
}

