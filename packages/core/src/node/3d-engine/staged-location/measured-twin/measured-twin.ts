/**
 * The measured procedural twin of a finished pipeline K build: the building generated by the native engine
 * (scratchbox_measured_twin.hpp, behind scripts/measured_twin.cpp) from what the build measured, with none of the scan's
 * surface in it. This module finds the build's records (its run notes, the facade orthos' frames, the kept window boxes,
 * the appearance classes and their library sets' prepared maps, the reveal depth when Street View read one) and hands
 * them to the generator as a line spec. The provenance of every part is the generator's (see its header); the reveal
 * depth's is decided here: photo-inferred when the reveal-depth stage read a trustworthy one, else a generated estimate.
 */

import { execFile } from 'child_process';
import * as fs from 'fs';
import * as path from 'path';
import { compileNativeCached, defaultNativeFlags, NativeBuildError, placeCachedBinary } from '../../native-build-cache';
import { loadTextureLibraryIndex } from '../../texture-library';
import { findTileRefineRepoRoot } from '../../tile-refine-service';
import { preparedKey } from '../pipeline-k/material-sets';
import type { ModelReadingStore } from '../pipeline-k/model-readings';
import { REVEAL_DEPTH_PARAMS } from '../reveal-depth';

export const MEASURED_TWIN_VERSION = 'measured-twin/2';

/** The reveal depth used when no reading is trusted (m): a plausible punched window's, labelled generated. */
export const GENERATED_REVEAL_M = 0.12;

/**
 * The scan analysis the twin's tiers come from: finer than pipeline E's shape program (which wants a short program),
 * because every setback is wanted as its own tier.
 */
export const TWIN_SCAN_PARAMS = { cell: 0.25, maxTiers: 16, minTierShare: 0.001, minTierArea: 4, modeMerge: 1.0 } as const;

type V3 = [number, number, number];
interface PlaneFrameJson { facadeId: number; image?: string; centroid: V3; normal: V3; axisS: V3; axisT: V3; orthoSMin: number; orthoTMax: number; pixel: number; width: number; height: number }
type Rect = [number, number, number, number];
interface WindowFitEntry { facadeId: number; width?: number; height?: number; rects?: Rect[]; panes?: Rect[]; generated?: Rect[]; error?: string }
interface MaterialClassNote { index: number; meanLab: V3; openings?: boolean; set?: string; finish?: { roughness?: number; metallic?: number; drawn?: { roughness?: number; metallic?: number } } }

/** What a K build left that the twin is made from, with the paths resolved on this machine. */
export interface KRunRecords {
    runDir: string;
    orthosDir: string;
    isolate: string;
    textured?: string;
    groundY: number;
    loops: Array<Array<[number, number]>>;
    planes: PlaneFrameJson[];
    windowFit: WindowFitEntry[];
    classes: MaterialClassNote[];
    /** Each plane's photo (its frame's pixels: the straightened ortho, else the twin reader's) and its uncovered mask. */
    photos: Record<number, { image: string; mask?: string }>;
    reveal: { depthM: number; label: 'photo-inferred' | 'generated'; source: string };
}

/**
 * A path a run note recorded, on this machine: as written when it exists, else its part from the cache's own folders
 * (tile_refine/, staged_location/) under `cacheRoot` (a build's cache copied or moved keeps its layout).
 */
export function rebasePath(p: string, cacheRoot: string): string {
    if (fs.existsSync(p)) return p;
    for (const seg of ['/tile_refine/', '/staged_location/']) {
        const i = p.lastIndexOf(seg);
        if (i >= 0) {
            const q = path.join(cacheRoot, p.slice(i + 1));
            if (fs.existsSync(q)) return q;
        }
    }
    return p;
}

const readJson = <T>(f: string): T | undefined => { try { return JSON.parse(fs.readFileSync(f, 'utf8')) as T; } catch { return undefined; } };

/** The records of a finished K build (its run folder under the staged cache). Throws with the missing record's name. */
export function readKRunRecords(runDir: string, cacheRoot: string): KRunRecords {
    const note = <T>(name: string) => readJson<T>(path.join(runDir, `${name}.json`));
    const k = note<{ orthosDir?: string; skipped?: string }>('pipeline_k');
    if (!k?.orthosDir) throw new Error(`no pipeline K facade work in this run (${path.join(runDir, 'pipeline_k.json')}${k?.skipped ? `: ${k.skipped}` : ''}); the measured twin is made from a pipeline K building`);
    const orthosDir = rebasePath(k.orthosDir, cacheRoot);
    if (!fs.existsSync(orthosDir)) throw new Error(`the run's facade orthos are not on this machine (${k.orthosDir})`);
    const refineDir = path.dirname(orthosDir);
    const isolate = path.join(refineDir, 'clay.glb');
    if (!fs.existsSync(isolate)) throw new Error(`the run's tree-free scan is not on this machine (${isolate})`);
    const textured = fs.existsSync(path.join(refineDir, 'textured.glb')) ? path.join(refineDir, 'textured.glb') : undefined;
    const base = note<{ loops?: Array<Array<[number, number]>>; groundY?: number }>('pipeline_k_base');
    if (!base?.loops?.length || typeof base.groundY !== 'number') throw new Error('the run has no footprint and ground level (pipeline_k_base.json)');
    const facades = readJson<{ facades: PlaneFrameJson[] }>(path.join(orthosDir, 'facades.json'))?.facades ?? [];
    // the other planes the reader read are framed by the twin reader's plane photos (its latest folder)
    const twinReads = fs.readdirSync(orthosDir).filter(d => d.startsWith('twin_read_')).map(d => path.join(orthosDir, d)).sort((a, b) => fs.statSync(b).mtimeMs - fs.statSync(a).mtimeMs);
    const others = twinReads.length ? readJson<{ planes: PlaneFrameJson[] }>(path.join(twinReads[0], 'planes.json'))?.planes ?? [] : [];
    // the photos: each facade's straightened ortho (the scan's own photo, straightened: the colours the elements are
    // sampled to), else the twin reader's photo of the plane (the planes tile_refine did not analyse)
    const photos: KRunRecords['photos'] = {};
    const sizeOk = (file: string, f: PlaneFrameJson) => { try { const b = fs.readFileSync(file); return b.length > 24 && b.readUInt32BE(16) === f.width && b.readUInt32BE(20) === f.height; } catch { return false; } };
    for (const f of [...facades, ...others]) {
        if (!f.image) continue;
        const dirs = twinReads.length ? [orthosDir, twinReads[0]] : [orthosDir];
        for (const d of dirs) {
            const image = path.join(d, f.image);
            if (!fs.existsSync(image) || !sizeOk(image, f)) continue;
            const mask = path.join(d, f.image.replace(/\.png$/, '_uncovered.png'));
            photos[f.facadeId] = { image, ...(fs.existsSync(mask) ? { mask } : {}) };
            break;
        }
    }
    const windowFit = readJson<{ facades: WindowFitEntry[] }>(path.join(orthosDir, 'window_fit.json'))?.facades;
    if (!windowFit) throw new Error(`the run has no window boxes (${path.join(orthosDir, 'window_fit.json')})`);
    const classes = note<{ classes?: MaterialClassNote[] }>('pipeline_k_materials')?.classes ?? [];
    const rd = note<{ skipped?: boolean; building?: { depthM: number; seM: number; pairs: number } }>('pipeline_k_reveal_depth');
    const trusted = rd && !rd.skipped && rd.building && rd.building.seM <= REVEAL_DEPTH_PARAMS.trustSeM && rd.building.depthM >= REVEAL_DEPTH_PARAMS.minT * rd.building.seM;
    const reveal = trusted
        ? { depthM: rd!.building!.depthM, label: 'photo-inferred' as const, source: `read from Street View by the reveal-depth stage: ${rd!.building!.depthM.toFixed(3)} +- ${rd!.building!.seM.toFixed(3)} m over ${rd!.building!.pairs} window pairs` }
        : { depthM: GENERATED_REVEAL_M, label: 'generated' as const, source: rd && !rd.skipped ? 'the reveal-depth stage read no depth it trusts; a plausible reveal' : 'no reveal-depth reading in this run (it needs Street View); a plausible reveal' };
    return { runDir, orthosDir, isolate, ...(textured ? { textured } : {}), groundY: base.groundY, loops: base.loops, planes: [...facades, ...others], windowFit, classes, photos, reveal };
}

const n6 = (v: number) => (Number.isFinite(v) ? String(Math.round(v * 1e6) / 1e6) : '0');

/**
 * The generator's line spec (scripts/measured_twin.cpp lists the directives). `maps` gives each class's prepared normal
 * and ORM PNG files and its set's real tile size, where known.
 */
export function measuredTwinSpec(r: KRunRecords, out: { glb: string; report: string }, maps: Array<{ normal?: string; orm?: string; tileM?: number } | undefined> = []): string {
    const L: string[] = [`# ${MEASURED_TWIN_VERSION} from ${r.runDir}`, `isolate ${r.isolate}`];
    if (r.textured) L.push(`textured ${r.textured}`);
    L.push(`out ${out.glb}`, `report ${out.report}`, `ground ${n6(r.groundY)}`);
    for (const l of r.loops) if (l.length >= 3) L.push(`footprint ${l.length} ${l.map(p => `${n6(p[0])} ${n6(p[1])}`).join(' ')}`);
    for (const [k, v] of Object.entries(TWIN_SCAN_PARAMS)) L.push(`scan ${k} ${v}`);
    L.push(`reveal ${n6(r.reveal.depthM)} ${r.reveal.label} ${r.reveal.source.replace(/\s+/g, ' ')}`);
    r.classes.forEach((c, i) => {
        const rough = c.finish?.drawn?.roughness ?? c.finish?.roughness ?? 0.8, metal = c.finish?.drawn?.metallic ?? c.finish?.metallic ?? 0;
        const m = maps[i];
        L.push(`class ${(c.set ?? `class${c.index}`).replace(/\s+/g, '_')} ${c.meanLab.map(n6).join(' ')} ${n6(rough)} ${n6(metal)} ${n6(m?.tileM ?? 2)} ${c.openings ? 1 : 0}`);
        if (m?.normal) L.push(`classnormal ${i} ${m.normal}`);
        if (m?.orm) L.push(`classorm ${i} ${m.orm}`);
    });
    const framed = new Map<number, PlaneFrameJson>();
    for (const f of r.planes) if (!framed.has(f.facadeId)) framed.set(f.facadeId, f);
    for (const [id, ph] of Object.entries(r.photos ?? {})) {
        if (!framed.has(Number(id))) continue;
        L.push(`planeimage ${id} ${ph.image}`);
        if (ph.mask) L.push(`planemask ${id} ${ph.mask}`);
    }
    for (const f of framed.values()) L.push(`plane ${f.facadeId} ${[...f.centroid, ...f.axisS, ...f.axisT, ...f.normal].map(n6).join(' ')} ${n6(f.orthoSMin)} ${n6(f.orthoTMax)} ${n6(f.pixel)} ${f.width} ${f.height}`);
    for (const e of r.windowFit) {
        if (e.error || !e.rects?.length) continue;
        const f = framed.get(e.facadeId);
        // a box is in its plane photo's pixels: a plane whose photo is not the one framed (another size) is left out
        if (!f || (e.width !== undefined && e.width !== f.width) || (e.height !== undefined && e.height !== f.height)) continue;
        const gen = new Set((e.generated ?? []).map(g => g.join(',')));
        for (const w of e.rects) L.push(`win ${e.facadeId} ${w.map(n6).join(' ')} ${gen.has(w.join(',')) ? 1 : 0}`);
        for (const p of e.panes ?? []) L.push(`pane ${e.facadeId} ${p.map(n6).join(' ')} 0`);
    }
    return L.join('\n') + '\n';
}

/**
 * Each class's library set's prepared maps (normal, ORM) from the model readings store, written under `dir`, and the
 * set's real tile size from the library index. A set the store does not hold has no maps (said in `missing`).
 */
export async function classMaps(classes: MaterialClassNote[], dir: string, store: ModelReadingStore | undefined, repoRoot = findTileRefineRepoRoot()): Promise<{ maps: Array<{ normal?: string; orm?: string; tileM?: number } | undefined>; missing: string[] }> {
    const index = loadTextureLibraryIndex(repoRoot);
    const missing: string[] = [];
    fs.mkdirSync(dir, { recursive: true });
    const maps = await Promise.all(classes.map(async c => {
        if (!c.set) return undefined;
        const entry = index?.sets.find(e => e.id === c.set);
        const tileM = entry?.realSizeM ? Math.max(...entry.realSizeM) : undefined;
        const rec = store ? await store.get<{ normal?: string; orm?: string }>(preparedKey(c.set)) : undefined;
        if (!rec?.normal || !rec.orm) { missing.push(c.set); return tileM ? { tileM } : undefined; }
        const normal = path.join(dir, `${c.set}_normal.png`), orm = path.join(dir, `${c.set}_orm.png`);
        fs.writeFileSync(normal, Buffer.from(rec.normal, 'base64'));
        fs.writeFileSync(orm, Buffer.from(rec.orm, 'base64'));
        return { normal, orm, ...(tileM ? { tileM } : {}) };
    }));
    return { maps, missing };
}

const CLI_SOURCE = path.join('scripts', 'measured_twin.cpp');
const INCLUDE_DIR = path.join('packages', 'core', 'src', 'native', '3d-engine', 'include');
const BINARY = path.join('build', '3d-native', 'measured_twin');
let building: Promise<string> | undefined;

/** Builds build/3d-native/measured_twin through the native build cache when its sources changed. */
export function ensureMeasuredTwinBinary(repoRoot = findTileRefineRepoRoot()): Promise<string> {
    building ??= (async () => {
        const bin = path.join(repoRoot, BINARY);
        try {
            const built = await compileNativeCached({ sourcePath: path.join(repoRoot, CLI_SOURCE), includeDirs: [path.join(repoRoot, INCLUDE_DIR)], flags: defaultNativeFlags(), libs: ['-lz'], name: 'measured_twin', timeoutMs: 600_000 });
            placeCachedBinary(built.binaryPath, bin);
            return bin;
        } catch (err) {
            throw new Error(`could not build measured_twin: ${err instanceof NativeBuildError ? err.compilerOutput.slice(-1500) : String(err)}`);
        }
    })().finally(() => { building = undefined; });
    return building;
}

/** The generator's report (scratchbox_measured_twin.hpp reportJson). */
export interface MeasuredTwinReport {
    ok: true; tiers: number; wallFaces: number; facesWithWindows: number; wallCells: number; roofCells: number; capsCut: number;
    detail: { faces: number; texels: number; atlas: [number, number]; texelM: number; paletteColours: number };
    windows: { given: number; placed: number; generated: number; continued: number; continueTested: number; rephased: number; wallsRephased: number; panes: number; dropped: Record<string, number> };
    colour: { elements: number; uncoloured: number };
    slender: { fromM: number | null; slices: number; bands: number };
    topM: number; revealM: number; revealLabel: string; triangles: number; bytes: number; classUse: Record<string, number>; notes: string[];
}

export interface MeasuredTwinResult {
    version: string; glb: string; specFile: string; report: MeasuredTwinReport; records: Omit<KRunRecords, 'planes' | 'windowFit' | 'photos'> & { planes: number; windowPlanes: number; photos: number }; mapsMissing: string[]; ms: number;
}

/**
 * Generates the measured twin of the K build in `runDir` into `outDir` (measured_twin.glb, its report and spec).
 * `store` is where the build's library maps were kept (its model readings store); without it the materials carry no maps.
 */
export async function buildMeasuredTwin(opts: { runDir: string; cacheRoot: string; outDir: string; store?: ModelReadingStore; signal?: AbortSignal; timeoutMs?: number }): Promise<MeasuredTwinResult> {
    const t0 = Date.now();
    const rec = readKRunRecords(opts.runDir, opts.cacheRoot);
    fs.mkdirSync(opts.outDir, { recursive: true });
    const { maps, missing } = await classMaps(rec.classes, path.join(opts.outDir, 'maps'), opts.store);
    const glb = path.join(opts.outDir, 'measured_twin.glb'), report = path.join(opts.outDir, 'measured_twin_report.json');
    const specFile = path.join(opts.outDir, 'measured_twin_spec.txt');
    fs.writeFileSync(specFile, measuredTwinSpec(rec, { glb, report }, maps));
    const bin = await ensureMeasuredTwinBinary();
    const stdout = await new Promise<string>((resolve, reject) => {
        execFile(bin, [specFile], { timeout: opts.timeoutMs ?? 600_000, killSignal: 'SIGKILL', maxBuffer: 16 * 1024 * 1024, ...(opts.signal ? { signal: opts.signal } : {}) }, (err, out, errOut) => {
            const tail = String(out || '').trim().split('\n').pop() ?? '';
            if (err) {
                let msg = tail || String(errOut || err.message).trim();
                try { msg = JSON.parse(tail).error ?? msg; } catch { /* not JSON */ }
                reject(new Error(`measured_twin failed: ${msg}`));
            } else resolve(tail);
        });
    });
    const answer = JSON.parse(stdout) as MeasuredTwinReport | { ok: false; error: string };
    if (!answer.ok) throw new Error(`measured_twin failed: ${(answer as { error: string }).error}`);
    const { planes, windowFit, photos, ...rest } = rec;
    return { version: MEASURED_TWIN_VERSION, glb, specFile, report: answer, records: { ...rest, planes: planes.length, windowPlanes: windowFit.filter(e => e.rects?.length).length, photos: Object.keys(photos).length }, mapsMissing: missing, ms: Date.now() - t0 };
}
