/**
 * The measured procedural twin of a finished pipeline K build: the building generated by the native engine
 * (scratchbox_measured_twin.hpp, behind scripts/measured_twin.cpp) from what the build measured, with none of the scan's
 * surface in it. This module finds the build's records (its run notes, the facade orthos' frames, the kept window boxes,
 * the appearance classes and their library sets' prepared maps, the reveal depth when Street View read one) and hands
 * them to the generator as a line spec. The provenance of every part is the generator's (see its header); the reveal
 * depth's is decided here: photo-inferred when the reveal-depth stage read a trustworthy one, else a generated estimate.
 */

