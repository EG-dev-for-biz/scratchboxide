#!/usr/bin/env node
/**
 * Generates docs/integrations/mcp/<category>.md from a live tools/list
 * response against the Scratchbox Canvas MCP server, or from a committed
 * JSON snapshot when no live endpoint/credentials are available.
 *
 * Usage:
 *   node scripts/generate_mcp_docs.mjs              # regenerate from committed snapshot
 *   node scripts/generate_mcp_docs.mjs --live        # fetch tools/list live, refresh snapshot, then regenerate
 *   node scripts/generate_mcp_docs.mjs --check       # regenerate into a temp dir and diff against committed docs (CI drift gate)
 *
 * Live mode reads connection details from env vars (see docs/integrations/mcp/README.md):
 *   SCRATCHBOX_MCP_ENDPOINT   default: https://scratchbox.ai/api/mcp/canvas
 *   SCRATCHBOX_MCP_SECRET     x-internal-secret header
 *   SCRATCHBOX_MCP_USER_ID    x-internal-user-id header
 *   SCRATCHBOX_MCP_WORKSPACE_ID  x-scratchbox-workspace-id header
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const DOCS_DIR = path.join(REPO_ROOT, 'docs', 'integrations', 'mcp');
const SNAPSHOT_PATH = path.join(DOCS_DIR, 'tools-snapshot.json');

const GENERATED_HEADER = (category) => `<!--
  AUTO-GENERATED by scripts/generate_mcp_docs.mjs — do not hand-edit.
  Source of truth: docs/integrations/mcp/tools-snapshot.json (refresh with --live).
  Category: ${category}
-->\n`;

// Longest-prefix match first so multi-word categories (e.g. "prompt_studio",
// "brand_kit", "learned_preferences") don't get split on their first underscore.
const CATEGORY_PREFIXES = [
    'prompt_studio', 'brand_kit', 'learned_preferences',
    'canvas', 'ai', 'video', 'audio', 'scene3d', 'location', 'writer',
    'storyboard', 'composition', 'character', 'flow', 'frame', 'operation',
    'library', 'publish', 'recipe', 'recipes', 'glossary', 'reference',
    'workspace', 'auth'
].sort((a, b) => b.length - a.length);

function categoryFor(toolName) {
    const short = toolName.replace(/^mcp__scratchbox__/, '');
    for (const prefix of CATEGORY_PREFIXES) {
        if (short === prefix || short.startsWith(prefix + '_')) return prefix;
    }
    return short.split('_')[0];
}

function shortName(toolName) {
    return toolName.replace(/^mcp__scratchbox__/, '');
}

function renderParamRow(name, schema, required) {
    const type = schema.enum ? `enum(${schema.enum.map((v) => JSON.stringify(v)).join(' \\| ')})`
        : schema.type === 'array' ? `array<${schema.items?.type || 'object'}>`
        : (schema.type || 'any');
    const constraints = [];
    if (schema.minLength !== undefined) constraints.push(`minLength ${schema.minLength}`);
    if (schema.maxLength !== undefined) constraints.push(`maxLength ${schema.maxLength}`);
    if (schema.minimum !== undefined) constraints.push(`min ${schema.minimum}`);
    if (schema.maximum !== undefined) constraints.push(`max ${schema.maximum}`);
    if (schema.minItems !== undefined) constraints.push(`minItems ${schema.minItems}`);
    if (schema.maxItems !== undefined) constraints.push(`maxItems ${schema.maxItems}`);
    if (schema.format) constraints.push(`format ${schema.format}`);
    const desc = [schema.description, constraints.length ? `_(${constraints.join(', ')})_` : '']
        .filter(Boolean).join(' ');
    return `| \`${name}\` | ${type} | ${required ? 'yes' : 'no'} | ${desc} |`;
}

function renderTool(tool) {
    const props = tool.inputSchema?.properties || {};
    const required = new Set(tool.inputSchema?.required || []);
    const rows = Object.entries(props).map(([name, schema]) => renderParamRow(name, schema, required.has(name)));
    const paramsTable = rows.length
        ? `| Parameter | Type | Required | Notes |\n|---|---|---|---|\n${rows.join('\n')}`
        : '_No parameters._';
    return `### \`${shortName(tool.name)}\`\n\n${tool.description}\n\n${paramsTable}\n`;
}

function renderCategoryDoc(category, tools) {
    const sorted = [...tools].sort((a, b) => shortName(a.name).localeCompare(shortName(b.name)));
    const toc = sorted.map((t) => `- [\`${shortName(t.name)}\`](#${shortName(t.name).replace(/_/g, '')})`).join('\n');
    return `${GENERATED_HEADER(category)}\n# ${category} tools\n\n${sorted.length} tool(s) in this category.\n\n${toc}\n\n---\n\n${sorted.map(renderTool).join('\n---\n\n')}`;
}

function renderIndex(byCategory) {
    const categories = Object.keys(byCategory).sort();
    const rows = categories.map((c) => `| [${c}](./${c}.md) | ${byCategory[c].length} |`);
    const total = categories.reduce((n, c) => n + byCategory[c].length, 0);
    return `${GENERATED_HEADER('index')}\n# Scratchbox Canvas MCP — Tool Catalog\n\n` +
        `Generated from a live \`tools/list\` snapshot. ${total} tools across ${categories.length} categories.\n` +
        `See [README.md](./README.md) for connection details, auth, and the async job pattern.\n\n` +
        `| Category | Tools |\n|---|---|\n${rows.join('\n')}\n`;
}

async function fetchLiveToolsList() {
    const endpoint = process.env.SCRATCHBOX_MCP_ENDPOINT || 'https://scratchbox.ai/api/mcp/canvas';
    const secret = process.env.SCRATCHBOX_MCP_SECRET;
    const userId = process.env.SCRATCHBOX_MCP_USER_ID;
    const workspaceId = process.env.SCRATCHBOX_MCP_WORKSPACE_ID;
    if (!secret || !userId) {
        throw new Error('SCRATCHBOX_MCP_SECRET and SCRATCHBOX_MCP_USER_ID must be set for --live mode.');
    }
    const res = await fetch(endpoint, {
        method: 'POST',
        headers: {
            'Content-Type': 'application/json',
            Accept: 'application/json, text/event-stream',
            'x-internal-secret': secret,
            'x-internal-user-id': userId,
            ...(workspaceId ? { 'x-scratchbox-workspace-id': workspaceId } : {})
        },
        body: JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'tools/list' })
    });
    if (!res.ok) throw new Error(`tools/list failed: ${res.status} ${res.statusText}`);
    const json = await res.json();
    const tools = json.result?.tools;
    if (!Array.isArray(tools)) throw new Error('Unexpected tools/list response shape');
    return tools;
}

function groupByCategory(tools) {
    const byCategory = {};
    for (const tool of tools) {
        const cat = categoryFor(tool.name);
        (byCategory[cat] ||= []).push(tool);
    }
    return byCategory;
}

function writeDocs(byCategory, outDir) {
    fs.mkdirSync(outDir, { recursive: true });
    for (const [category, tools] of Object.entries(byCategory)) {
        fs.writeFileSync(path.join(outDir, `${category}.md`), renderCategoryDoc(category, tools));
    }
    fs.writeFileSync(path.join(outDir, 'index.md'), renderIndex(byCategory));
}

async function main() {
    const args = process.argv.slice(2);
    const live = args.includes('--live');
    const check = args.includes('--check');

    let tools;
    if (live) {
        tools = await fetchLiveToolsList();
        fs.writeFileSync(SNAPSHOT_PATH, JSON.stringify({ capturedAt: new Date().toISOString(), tools }, null, 2));
    } else {
        if (!fs.existsSync(SNAPSHOT_PATH)) {
            console.error(`No snapshot at ${SNAPSHOT_PATH}. Run with --live first (requires MCP credentials).`);
            process.exit(1);
        }
        tools = JSON.parse(fs.readFileSync(SNAPSHOT_PATH, 'utf-8')).tools;
    }

    const byCategory = groupByCategory(tools);

    if (check) {
        const tmpDir = fs.mkdtempSync(path.join(REPO_ROOT, '.mcp-docs-check-'));
        try {
            writeDocs(byCategory, tmpDir);
            const committedFiles = fs.readdirSync(DOCS_DIR).filter((f) => f.endsWith('.md') && f !== 'README.md');
            const freshFiles = fs.readdirSync(tmpDir);
            const drifted = [];
            for (const f of new Set([...committedFiles, ...freshFiles])) {
                const committed = fs.existsSync(path.join(DOCS_DIR, f)) ? fs.readFileSync(path.join(DOCS_DIR, f), 'utf-8') : null;
                const fresh = fs.existsSync(path.join(tmpDir, f)) ? fs.readFileSync(path.join(tmpDir, f), 'utf-8') : null;
                if (committed !== fresh) drifted.push(f);
            }
            if (drifted.length) {
                console.error(`MCP docs are stale. Re-run "node scripts/generate_mcp_docs.mjs" and commit the diff. Drifted: ${drifted.join(', ')}`);
                process.exit(1);
            }
            console.log('MCP docs are up to date.');
        } finally {
            fs.rmSync(tmpDir, { recursive: true, force: true });
        }
        return;
    }

    writeDocs(byCategory, DOCS_DIR);
    const total = Object.values(byCategory).reduce((n, t) => n + t.length, 0);
    console.log(`Wrote ${Object.keys(byCategory).length} category files (${total} tools) to ${DOCS_DIR}`);
}

main().catch((err) => {
    console.error(err);
    process.exit(1);
});
